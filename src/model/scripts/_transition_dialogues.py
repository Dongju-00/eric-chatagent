def transition_sessions(count=400):
    if not 0 <= count <= 400:
        raise ValueError('Available authored variations: 0–400; more require new dialogue arcs.')
    result = []
    for arc in _ARCS.split('\n\n'):
        pairs = [tuple(line.split('\t', 1)) for line in arc.splitlines()]
        for company in COMPANIES:
            result.append([(q.format(company=company), a.format(company=company)) for q, a in pairs])
    return result[:count]
